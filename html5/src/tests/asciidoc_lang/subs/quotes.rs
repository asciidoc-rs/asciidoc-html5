// For blocks, the step's name `quotes` can be assigned to `subs`; for inline
// text, the built-in values `q` or `quotes` add the step through the inline
// pass macro.
#[test]
fn quotes_value() {
    verifies!(
        r#"
The quotes substitution step can be modified on blocks and inline elements.
For blocks, the step's name, `quotes`, can be assigned to the xref:apply-subs-to-blocks.adoc[subs attribute].
For inline elements, the built-in values `q` or `quotes` can be applied to xref:apply-subs-to-text.adoc[inline text] to add the quotes substitution step.
"#
    );

    // Adding `quotes` to a source block's default group formats the markup that
    // a verbatim block would otherwise leave literal.
    let block = convert("[source,java,subs=\"verbatim,quotes\"]\n----\nSystem.out.println(\"Hello *bold*\")\n----\n");
    assert!(block.contains("Hello <strong>bold</strong>"));

    // The inline `q` shorthand on the pass macro formats the enclosed markup.
    let inline = convert("pass:q[*bold* _em_]\n");
    assert!(inline.contains("<strong>bold</strong> <em>em</em>"));
}

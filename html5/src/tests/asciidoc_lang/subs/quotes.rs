//! Coverage of the AsciiDoc language description's *Quotes Substitutions* page.
//!
//! The quotes step replaces inline formatting markup with the corresponding
//! HTML. This crate performs every mapping the page tabulates through
//! `convert`, so the worked example, the AsciiDoc-to-HTML mapping table, and
//! the `quotes`/`q` substitution values are verified. The applicability table
//! is descriptive and tracked as non-normative.

use super::applicability::ran;
use crate::{convert, tests::sdd::*};

track_file!("ref/asciidoc-lang/docs/modules/subs/pages/quotes.adoc");

non_normative!(
    r#"
= Quotes Substitutions
:navtitle: Quotes
:table-caption: Table
:y: Yes
//icon:check[role="green"]
:n: No
//icon:times[role="red"]

"#
);

// The quotes step replaces the formatting marks around inline text with the
// matching HTML tags: a `*…*` pair becomes a `<strong>` element.
#[test]
fn quotes_step() {
    verifies!(
        r#"
The replacement of the formatting markup on inline elements is called the quotes substitution step.

.Syntax input
[source#ex-quotes]
----
Happy werewolves are *really* slobbery.
----

For instance, when a document containing the markup in <<ex-quotes>> is converted to HTML, any asterisks enclosing text are replaced with the start and end tags of the `<strong>` element.
The resulting HTML can be seen in <<ex-html>> below.

.HTML output
[source#ex-html,html]
----
Happy werewolves are <strong>really</strong> slobbery.
----

"#
    );

    let out = convert("Happy werewolves are *really* slobbery.\n");
    assert!(out.contains("Happy werewolves are <strong>really</strong> slobbery."));
}

// Each inline formatting syntax the page tabulates maps to the shown HTML.
#[test]
fn quotes_html_table() {
    verifies!(
        r#"
<<table-quotes-html>> shows the HTML source code that is generated by the quotes substitution step.

.HTML source code generated from AsciiDoc formatting syntax
[#table-quotes-html%autowidth,cols="~,^~,^~"]
|===
|Name |AsciiDoc |HTML

|emphasis
|+_word_+
|<em>word</em>

|strong
|+*word*+
|<strong>word</strong>

|monospace
|+`word`+
|<code>word</code>

|superscript
|+^word^+
|<sup>word</sup>

|subscript
|+~word~+
|<sub>word</sub>

|double curved quotes
|+"`word`"+
|+&#8220;word&#8221;+

|single curved quotes
|+'`word`'+
|+&#8216;word&#8217;+
|===

"#
    );

    assert!(convert("_word_\n").contains("<em>word</em>"));
    assert!(convert("*word*\n").contains("<strong>word</strong>"));
    assert!(convert("`word`\n").contains("<code>word</code>"));
    assert!(convert("^word^\n").contains("<sup>word</sup>"));
    assert!(convert("~word~\n").contains("<sub>word</sub>"));
    assert!(convert("\"`word`\"\n").contains("&#8220;word&#8221;"));
    assert!(convert("'`word`'\n").contains("&#8216;word&#8217;"));
}


/// Renders `input` as a standalone document — the counterpart to Asciidoctor's
/// `convert_string` (the embedded `convert` maps to Asciidoctor's
/// `convert_string_to_embedded`).
fn convert_standalone(input: &str) -> String {
    convert_with(input, &Options::new().standalone(true))
}

/// Counts the warnings the parser raises for `input` whose type matches `pred`
/// — the rendered-pipeline counterpart to Asciidoctor's `assert_message
/// @logger, :WARN, …`. (The parser reflects these diagnostics in the document's
/// warnings inventory.)
fn count_warnings(input: &str, pred: impl Fn(&WarningType) -> bool) -> usize {
    load(input).warnings().filter(|w| pred(&w.warning)).count()
}

